_TABLES = {"de": DE}


def translate(lang: str, s: str) -> str:
    table = _TABLES.get(lang)
    if not table:
        return s
    return table.get(s, s)


def make_translator(lang: str):
    if lang in _TABLES:
        return lambda s: translate(lang, s) if s else s
    return lambda s: s
